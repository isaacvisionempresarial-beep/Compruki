import { createServerClient } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";
import { supabaseAnonKey, supabaseUrl } from "@/lib/supabase/env";

/** Intercambia el código del correo de recuperación y lleva al formulario de nueva clave. */
export async function GET(request: NextRequest) {
  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get("code");
  const next = searchParams.get("next") || "/ingresar?modo=nueva-clave";

  if (!code) {
    return NextResponse.redirect(`${origin}/ingresar?error=enlace`);
  }

  let response = NextResponse.redirect(`${origin}${next.startsWith("/") ? next : `/${next}`}`);

  const supabase = createServerClient(supabaseUrl(), supabaseAnonKey(), {
    cookies: {
      getAll() {
        return request.cookies.getAll();
      },
      setAll(cookiesToSet) {
        cookiesToSet.forEach(({ name, value }) => request.cookies.set(name, value));
        response = NextResponse.redirect(`${origin}${next.startsWith("/") ? next : `/${next}`}`);
        cookiesToSet.forEach(({ name, value, options }) => response.cookies.set(name, value, options));
      },
    },
  });

  const { error } = await supabase.auth.exchangeCodeForSession(code);
  if (error) {
    return NextResponse.redirect(`${origin}/ingresar?error=enlace`);
  }

  return response;
}
